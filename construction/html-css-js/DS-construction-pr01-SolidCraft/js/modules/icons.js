/* Builds a decorative <svg> for a registry key, or null when the key is unknown.
   The surrounding link/button keeps ownership of the accessible name. */
function createIcon(name) {
  const icon = ICONS[name];
  if (!icon) return null;

  const svg = document.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", icon.viewBox);
  svg.setAttribute("fill", "currentColor");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");

  for (const d of icon.paths) {
    const path = document.createElementNS(SVG_NS, "path");
    path.setAttribute("d", d);
    svg.appendChild(path);
  }

  return svg;
}

/* Resolves every [data-icon] placeholder inside root. Unknown keys are left
   untouched so unrelated data-icon usage never breaks. */
function initIcons(root = document) {
  const scope =
    root && typeof root.querySelectorAll === "function" ? root : document;

  for (const el of scope.querySelectorAll("[data-icon]")) {
    const svg = createIcon(el.dataset.icon);
    if (!svg) continue;
    el.replaceChildren(svg);
  }
}

